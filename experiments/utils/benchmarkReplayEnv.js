function createBenchmarkReplayRunEnv(baseEnv = process.env) {
  const runStartTime =
    baseEnv.STREAMING_QUERY_HIVE_BENCHMARK_START_TIME || `${Date.now()}`;

  function withBenchmarkReplayEnv(env = {}) {
    return {
      ...env,
      LOG_PATH: env.LOG_PATH || baseEnv.LOG_PATH || "",
      HIVE_PROFILE: env.HIVE_PROFILE || baseEnv.HIVE_PROFILE || "",
      HIVE_PROFILE_OUTPUT_DIR:
        env.HIVE_PROFILE_OUTPUT_DIR || baseEnv.HIVE_PROFILE_OUTPUT_DIR || "",
      HIVE_PROFILE_OUTPUT_FILE:
        env.HIVE_PROFILE_OUTPUT_FILE || baseEnv.HIVE_PROFILE_OUTPUT_FILE || "",
      STREAMING_QUERY_HIVE_DETERMINISTIC_EVENT_TIME:
        env.STREAMING_QUERY_HIVE_DETERMINISTIC_EVENT_TIME ||
        baseEnv.STREAMING_QUERY_HIVE_DETERMINISTIC_EVENT_TIME ||
        "1",
      STREAMING_QUERY_HIVE_CHUNKED_COMPARABLE_OUTPUT_ONLY:
        env.STREAMING_QUERY_HIVE_CHUNKED_COMPARABLE_OUTPUT_ONLY ||
        baseEnv.STREAMING_QUERY_HIVE_CHUNKED_COMPARABLE_OUTPUT_ONLY ||
        "1",
      STREAMING_QUERY_HIVE_CHUNKED_CADENCE_ONLY:
        env.STREAMING_QUERY_HIVE_CHUNKED_CADENCE_ONLY ||
        baseEnv.STREAMING_QUERY_HIVE_CHUNKED_CADENCE_ONLY ||
        "0",
      STREAMING_QUERY_HIVE_CHUNKED_USE_IMMEDIATE_TRIGGER:
        env.STREAMING_QUERY_HIVE_CHUNKED_USE_IMMEDIATE_TRIGGER ||
        baseEnv.STREAMING_QUERY_HIVE_CHUNKED_USE_IMMEDIATE_TRIGGER ||
        "1",
      STREAMING_QUERY_HIVE_APPROXIMATION_COMPLETED_WINDOW_MODE:
        env.STREAMING_QUERY_HIVE_APPROXIMATION_COMPLETED_WINDOW_MODE ||
        baseEnv.STREAMING_QUERY_HIVE_APPROXIMATION_COMPLETED_WINDOW_MODE ||
        "1",
      STREAMING_QUERY_HIVE_APPROXIMATION_EARLY_TRIGGER_MODE:
        env.STREAMING_QUERY_HIVE_APPROXIMATION_EARLY_TRIGGER_MODE ||
        baseEnv.STREAMING_QUERY_HIVE_APPROXIMATION_EARLY_TRIGGER_MODE ||
        "0",
      STREAMING_QUERY_HIVE_BENCHMARK_START_TIME:
        env.STREAMING_QUERY_HIVE_BENCHMARK_START_TIME ||
        baseEnv.STREAMING_QUERY_HIVE_BENCHMARK_START_TIME ||
        runStartTime,
      STREAMING_QUERY_HIVE_BENCHMARK_EVENT_TIME_ANCHOR:
        env.STREAMING_QUERY_HIVE_BENCHMARK_EVENT_TIME_ANCHOR ||
        baseEnv.STREAMING_QUERY_HIVE_BENCHMARK_EVENT_TIME_ANCHOR ||
        runStartTime,
    };
  }

  return {
    runStartTime,
    withBenchmarkReplayEnv,
  };
}

module.exports = {
  createBenchmarkReplayRunEnv,
};
